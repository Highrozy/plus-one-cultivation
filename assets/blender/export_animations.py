# Export every animation (Action) on the R15Rig armature into src/shared/AnimationData.luau.
#
# How to use after editing animations in Blender:
#   Scripting tab -> open this file -> Run Script. Then Rojo syncs the new data into Studio.
#   (Re-publish the animation in Studio if you want the uploaded asset to match.)
#
# The rig's bones all have identity rest orientation, so each pose bone's rotation/location
# is already in character space. We only convert Blender axes to Roblox axes:
#   Roblox X = -Blender X, Roblox Y = Blender Z, Roblox Z = Blender Y.

import bpy
import os
from mathutils import Matrix

REPO = r"C:\Users\lberr\Projects\plus-one-cultivation"
OUT = os.path.join(REPO, "src", "shared", "AnimationData.luau")
RIG = "R15Rig"

M = Matrix(((-1, 0, 0), (0, 0, 1), (0, 1, 0)))
M_T = M.transposed()


def to_roblox(pose_bone):
    rot = M @ pose_bone.rotation_quaternion.to_matrix() @ M_T
    pos = M @ pose_bone.location
    values = [pos.x, pos.y, pos.z]
    for r in range(3):
        for c in range(3):
            values.append(rot[r][c])
    return values


def animated_bones(action):
    names = set()
    fcurves = list(getattr(action, "fcurves", []) or [])
    if not fcurves:  # Blender 4.4+ layered actions
        for layer in getattr(action, "layers", []):
            for strip in layer.strips:
                for bag in strip.channelbags:
                    fcurves.extend(bag.fcurves)
    for fc in fcurves:
        if fc.data_path.startswith('pose.bones["'):
            names.add(fc.data_path.split('"')[1])
    return sorted(names)


def fmt(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def export():
    scene = bpy.context.scene
    arm = bpy.data.objects[RIG]
    fps = scene.render.fps
    parents = {b.name: (b.parent.name if b.parent else None) for b in arm.data.bones}
    saved_action = arm.animation_data.action if arm.animation_data else None

    lines = [
        "--!strict",
        "-- AUTO-GENERATED by assets/blender/export_animations.py from plus1_animations.blend.",
        "-- Do not edit by hand: edit the animation in Blender and re-run the export script.",
        "--",
        "-- Each animation: Length (seconds) and Keyframes. Each keyframe has a Time and Poses:",
        "-- part name -> CFrame components {x, y, z, R00..R22} for that part's joint (Roblox axes).",
        "-- Parents lists every animated part's parent, so a KeyframeSequence can be built from this.",
        "",
        "return {",
        "\tParents = {",
    ]
    for name, parent in sorted(parents.items()):
        if parent:
            lines.append(f'\t\t{name} = "{parent}",')
    lines.append("\t},")
    lines.append("\tAnimations = {")

    for action in sorted(bpy.data.actions, key=lambda a: a.name):
        bones = animated_bones(action)
        if not bones:
            continue
        arm.animation_data.action = action
        if hasattr(arm.animation_data, "action_slot") and arm.animation_data.action_slot is None and action.slots:
            arm.animation_data.action_slot = action.slots[0]
        start, end = (int(f) for f in action.frame_range)
        lines.append(f"\t\t{action.name} = {{")
        lines.append(f"\t\t\tLength = {fmt((end - start) / fps)},")
        lines.append("\t\t\tKeyframes = {")
        for frame in range(start, end + 1):
            scene.frame_set(frame)
            lines.append(f"\t\t\t\t{{ Time = {fmt((frame - start) / fps)}, Poses = {{")
            for name in bones:
                values = ", ".join(fmt(v) for v in to_roblox(arm.pose.bones[name]))
                lines.append(f"\t\t\t\t\t{name} = {{ {values} }},")
            lines.append("\t\t\t\t} },")
        lines.append("\t\t\t},")
        lines.append("\t\t},")

    lines.append("\t},")
    lines.append("}")
    lines.append("")

    arm.animation_data.action = saved_action
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    return OUT


result = {"written": export()}
